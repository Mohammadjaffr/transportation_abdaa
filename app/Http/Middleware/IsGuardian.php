<?php

namespace App\Http\Middleware;

use Closure;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;
use Symfony\Component\HttpFoundation\Response;

class IsGuardian
{
    /**
     * Handle an incoming request.
     */
    public function handle(
        Request $request,
        Closure $next
    ): Response {

        $user = Auth::user();


        /*
        |--------------------------------------------------------------------------
        | المستخدم غير مسجل الدخول
        |--------------------------------------------------------------------------
        */

        if (!$user) {
            return redirect()->route('login');
        }


        /*
        |--------------------------------------------------------------------------
        | إذا كان Admin
        |--------------------------------------------------------------------------
        |
        | لا نسمح له بدخول بوابة ولي الأمر من هذا المسار.
        |
        */

        if ($user->role === 'admin') {

            return redirect()
                ->route('home')
                ->with(
                    'error',
                    'هذه الصفحة مخصصة لأولياء الأمور فقط.'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | إذا كان Driver
        |--------------------------------------------------------------------------
        */

        if ($user->role === 'driver') {

            return redirect()
                ->route('driver.dashboard')
                ->with(
                    'error',
                    'هذه الصفحة مخصصة لأولياء الأمور فقط.'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | يجب أن يكون Guardian
        |--------------------------------------------------------------------------
        */

        if ($user->role !== 'guardian') {

            abort(
                403,
                'لا تملك صلاحية الدخول إلى بوابة ولي الأمر.'
            );
        }


        /*
        |--------------------------------------------------------------------------
        | يجب أن يكون الحساب مرتبطًا بولي أمر
        |--------------------------------------------------------------------------
        */

        if (empty($user->guardian_id)) {

            Auth::logout();

            $request
                ->session()
                ->invalidate();

            $request
                ->session()
                ->regenerateToken();


            return redirect()
                ->route('login')
                ->withErrors([
                    'name' =>
                    'هذا الحساب غير مرتبط بولي أمر.'
                ]);
        }


        /*
        |--------------------------------------------------------------------------
        | حساب المستخدم محظور
        |--------------------------------------------------------------------------
        */

        if ($user->is_banned) {

            Auth::logout();

            $request
                ->session()
                ->invalidate();

            $request
                ->session()
                ->regenerateToken();


            return redirect()
                ->route('login')
                ->withErrors([
                    'name' =>
                    'عذراً، هذا الحساب محظور من الإدارة ولا يمكنك الدخول.'
                ]);
        }


        /*
        |--------------------------------------------------------------------------
        | التأكد من وجود Guardian
        |--------------------------------------------------------------------------
        */

        $guardian = $user->guardian;


        if (!$guardian) {

            Auth::logout();

            $request
                ->session()
                ->invalidate();

            $request
                ->session()
                ->regenerateToken();


            return redirect()
                ->route('login')
                ->withErrors([
                    'name' =>
                    'تعذر العثور على بيانات ولي الأمر المرتبطة بهذا الحساب.'
                ]);
        }


        /*
        |--------------------------------------------------------------------------
        | التأكد أن ولي الأمر مفعل
        |--------------------------------------------------------------------------
        */

        if (!$guardian->is_active) {

            Auth::logout();

            $request
                ->session()
                ->invalidate();

            $request
                ->session()
                ->regenerateToken();


            return redirect()
                ->route('login')
                ->withErrors([
                    'name' =>
                    'حساب ولي الأمر موقوف حالياً. يرجى مراجعة الإدارة.'
                ]);
        }


        /*
        |--------------------------------------------------------------------------
        | كل شيء صحيح
        |--------------------------------------------------------------------------
        */

        return $next($request);
    }
}